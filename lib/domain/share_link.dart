/// 共有リンクを受け入れられない理由（仕様書 3.3）
///
/// **判定そのものはサーバー側にある**（`functions/src/domain/share_link.ts`）。
/// クライアントに同じ判定を置くと、テストは緑なのに本番では別のコードが
/// 動く状態になる。過去に実際そうなっていた（監査 S11・第2回）。
/// ここに置くのは、**画面が文言を出し分けるための符号だけ**。
///
/// 以前の招待 URL は「一度きり・24 時間」だったため、
/// 「期限切れ」「使用済み」「すでにメンバー」という理由があった。
/// **無期限・何度でも・複数人**に変えたので、どれも無くなっている。
library;

enum ShareLinkRejection {
  /// リンクそのものが存在しない（URL が誤っている）。
  notFound,

  /// 発行した人が取り消した（3.3）。
  ///
  /// **期限が無いぶん、これが唯一の止める手段。**
  revoked,
}
